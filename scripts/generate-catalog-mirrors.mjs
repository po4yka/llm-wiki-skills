import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  escapeTableCell,
  firstSentence,
  readCatalogModel,
  readDocsRecords,
} from './lib/skill-catalog.mjs';
import { readText, repoRoot } from './lib/repo.mjs';

function replaceSection(markdown, heading, replacementLines) {
  const lines = markdown.split('\n');
  const start = lines.findIndex((line) => line === heading);

  if (start === -1) {
    throw new Error(`Cannot find section heading '${heading}'`);
  }

  const level = heading.match(/^#+/)?.[0].length;
  const next = lines.findIndex((line, index) => {
    if (index <= start) return false;
    const match = line.match(/^(#+)\s+/);
    return match && match[1].length <= level;
  });

  const end = next === -1 ? lines.length : next;
  const nextChunk = next === -1 ? [] : lines.slice(end);

  return [...lines.slice(0, start), ...replacementLines, ...nextChunk].join('\n').replace(/\n*$/, '\n');
}

function writeMarkdown(repoPath, content) {
  const absPath = path.join(repoRoot, repoPath);
  fs.writeFileSync(absPath, content);
  console.log(`✓ generated ${repoPath}`);
}

export function buildSkillFamiliesSection() {
  const { manifest, skillMap } = readCatalogModel();
  const lines = [
    '## Skill families',
    '',
    '<!-- generated:skill-families:start -->',
    '<!-- Generated by `npm run catalog:generate`. Do not edit this block by hand. -->',
    '',
  ];

  manifest.groupings.forEach((group, index) => {
    lines.push(`### ${group.title}`, '', group.description, '', '| Skill | Purpose |', '|---|---|');

    for (const skillName of group.skills) {
      const skill = skillMap.get(skillName);
      lines.push(
        `| [\`${skillName}\`](../skills/${skillName}/SKILL.md) | ${escapeTableCell(firstSentence(skill.description))} |`,
      );
    }

    if (index < manifest.groupings.length - 1) {
      lines.push('');
    }
  });

  lines.push('', '<!-- generated:skill-families:end -->', '');
  return lines;
}

export function buildDocumentMapSection() {
  const records = readDocsRecords();
  const lines = [
    '## Document map',
    '',
    '> Numbering policy: numeric prefixes are reserved for the architecture series. Adoption documents use stable named slugs so a prefix identifies at most one root document.',
    '',
    '<!-- generated:document-map:start -->',
    '<!-- Generated by `npm run catalog:generate`. Do not edit this block by hand. -->',
    '',
    '| Document | Title | Scope | Freshness |',
    '|---|---|---|---|',
  ];

  for (const record of records) {
    const scope = record.scope ?? firstSentence(record.title);
    lines.push(
      `| [\`${record.path}\`](${record.path}) | ${escapeTableCell(record.title)} | ${escapeTableCell(scope)} | ${escapeTableCell(record.currentAsOf ?? '')} |`,
    );
  }

  lines.push('', '<!-- generated:document-map:end -->', '');
  return lines;
}

export function buildRouteInventorySection() {
  const { router, routeMap, skills } = readCatalogModel();
  const lines = [
    '## Route inventory',
    '',
    '<!-- generated:route-inventory:start -->',
    '<!-- Generated by `npm run catalog:generate`. Do not edit this block by hand. -->',
    '',
    '| Skill | Primary intents | Not for | Risk | Web | Mode | Next |',
    '|---|---|---|---|---|---|---|',
  ];

  for (const skill of skills) {
    const route = routeMap.get(skill.name);
    lines.push(
      [
        `| [\`${skill.name}\`](../skills/${skill.name}/SKILL.md)`,
        escapeTableCell((route?.intents ?? []).join('; ')),
        escapeTableCell((route?.not_for ?? []).join('; ')),
        escapeTableCell(route?.write_risk ?? ''),
        route?.requires_web === true ? 'yes' : 'no',
        escapeTableCell(route?.default_mode ?? ''),
        escapeTableCell((route?.next ?? []).join(', ')),
      ].join(' | ') + ' |',
    );
  }

  lines.push(
    '',
    `Default entrypoints: ${router.default_entrypoints.map((skill) => `\`${skill}\``).join(', ')}.`,
    '',
    '<!-- generated:route-inventory:end -->',
    '',
  );
  return lines;
}

export function buildGeneratedMirrors() {
  const overviewPath = 'docs/07-skills-overview.md';
  const indexPath = 'docs/00-index.md';
  const routerDocPath = 'docs/skill-router.md';
  const routerDoc = readText(path.join(repoRoot, routerDocPath));
  const routerReplacement = routerDoc.includes('\n## Route inventory\n')
    ? replaceSection(routerDoc, '## Route inventory', buildRouteInventorySection())
    : replaceSection(routerDoc, '## Skill authoring', [
        ...buildRouteInventorySection(),
        '## Skill authoring',
        '',
      ]);

  return new Map([
    [
      overviewPath,
      replaceSection(readText(path.join(repoRoot, overviewPath)), '## Skill families', buildSkillFamiliesSection()),
    ],
    [
      indexPath,
      replaceSection(readText(path.join(repoRoot, indexPath)), '## Document map', buildDocumentMapSection()),
    ],
    [routerDocPath, routerReplacement],
  ]);
}

export function writeGeneratedMirrors() {
  for (const [repoPath, content] of buildGeneratedMirrors()) {
    writeMarkdown(repoPath, content);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeGeneratedMirrors();
}
